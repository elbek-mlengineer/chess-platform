export const onlineDictionaries: Record<Locale, OnlineDictionary> = {
  en,
  uz,
  ru,
};
export function onlineErrorText(locale: Locale, code: string) {
  const errors = onlineDictionaries[locale].errors;
  return (
    Object.entries(errors).find(([key]) => key === code)?.[1] ||
    errors.serverError
  );
}
